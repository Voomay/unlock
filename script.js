// Custom Trip Quote Builder Handler
function submitQuoteBuilder(channel) {
  const name = document.getElementById("guestName").value.trim() || "Guest";
  const guests = document.getElementById("guestCount").value;
  const date = document.getElementById("tourDate").value || "Flexible dates";
  const pickup = document.getElementById("pickupLocation").value.trim() || "Cape Town area";
  const notes = document.getElementById("guestNotes").value.trim();

  const checkedBoxes = Array.from(
    document.querySelectorAll('input[name="selectedTours"]:checked')
  ).map((cb) => cb.value);

  const toursList =
    checkedBoxes.length > 0
      ? checkedBoxes.map((t) => `  • ${t}`).join("\n")
      : "  • General Private Tour / Custom Recommendation";

  const message =
    `Hello Louis! 👋\n\n` +
    `I'd like to request a custom tour quote from Unlock Cape Town Tours:\n\n` +
    `*Name:* ${name}\n` +
    `*Group Size:* ${guests}\n` +
    `*Preferred Date(s):* ${date}\n` +
    `*Pickup Location:* ${pickup}\n\n` +
    `*Experiences of Interest:*\n${toursList}\n` +
    (notes ? `\n*Additional Notes:* ${notes}\n` : "") +
    `\nPlease let me know availability and a tailored quote. Thank you!`;

  if (channel === "whatsapp") {
    window.open(buildWhatsAppUrl(message), "_blank", "noopener");
  } else {
    const subject = `Custom Tour Quote Request — ${name} (${guests})`;
    window.location.href = buildMailtoUrl(subject, message.replace(/\*/g, ""));
  }
}

document.addEventListener("DOMContentLoaded", () => {
  // Sticky navbar scroll shadow
  const navbar = document.getElementById("navbar");
  window.addEventListener("scroll", () => {
    if (window.scrollY > 25) {
      navbar.classList.add("scrolled");
    } else {
      navbar.classList.remove("scrolled");
    }
  });

  // Mobile Menu toggle
  const mobileBtn = document.getElementById("mobileMenuBtn");
  const navLinks = document.getElementById("navLinks");
  if (mobileBtn && navLinks) {
    mobileBtn.addEventListener("click", () => {
      navLinks.classList.toggle("open");
    });
    navLinks.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => navLinks.classList.remove("open"));
    });
  }

  // Category filter buttons
  const filterBtns = document.querySelectorAll(".filter-btn");
  const tourCards = document.querySelectorAll(".tour-card");

  filterBtns.forEach((btn) => {
    btn.addEventListener("click", () => {
      filterBtns.forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");

      const filter = btn.getAttribute("data-filter");
      tourCards.forEach((card) => {
        const categories = card.getAttribute("data-category");
        if (filter === "all" || categories.includes(filter)) {
          card.style.display = "flex";
        } else {
          card.style.display = "none";
        }
      });
    });
  });

  // FAQ Accordion
  document.querySelectorAll(".faq-question").forEach((btn) => {
    btn.addEventListener("click", () => {
      const item = btn.parentElement;
      const wasOpen = item.classList.contains("open");
      document.querySelectorAll(".faq-item").forEach((el) => el.classList.remove("open"));
      if (!wasOpen) {
        item.classList.add("open");
      }
    });
  });

  // Close modal on backdrop click or Escape key
  const modal = document.getElementById("tourModal");
  if (modal) {
    modal.addEventListener("click", (e) => {
      if (e.target === modal) closeTourModal();
    });
  }
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") closeTourModal();
  });
});
